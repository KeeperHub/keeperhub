// ---------------------------------------------------------------------------
// Expression -> ConditionGroup parser (reverse of visualConditionToExpression)
// Parses expressions generated by the visual builder AND simple user-typed
// expressions. Returns null when the expression can't be parsed.
// ---------------------------------------------------------------------------

// Top-level regex patterns for parseAtomicExpression (biome: useTopLevelRegex)
const STRING_METHOD_PATTERN =
  /^String\((.+?)\)\.(includes|startsWith|endsWith)\((.+)\)$/;
const IS_EMPTY_PATTERN =
  /^(.+?) === null \|\| \1 === undefined \|\| \1 === ""$/;
const IS_NOT_EMPTY_PATTERN =
  /^(.+?) !== null && \1 !== undefined && \1 !== ""$/;
const EXISTS_PATTERN = /^(.+?) !== null && \1 !== undefined$/;
const DOES_NOT_EXIST_PATTERN = /^(.+?) === null \|\| \1 === undefined$/;
const IS_NULL_PATTERN = /^(.+?) === null$/;
const IS_NOT_NULL_PATTERN = /^(.+?) !== null$/;
const IS_UNDEFINED_PATTERN = /^(.+?) === undefined$/;
const IS_NOT_UNDEFINED_PATTERN = /^(.+?) !== undefined$/;
const LINE_BREAK = /[\n\r\u2028\u2029]/;
const MAX_PARSED_MULTILINE = 10_000;
// The spaces before the operator start only where a run of spaces does: the
// same matches, without rescanning a long run at every position.
const COMPARISON_PATTERN = /^(.+?)(?<!\s)\s+(===|!==|==|!=|>=|<=|>|<)\s+(.+)$/;
// What String#trim removes.
const WHITESPACE = /\s/;

/**
 * Condition text with its masked structure, same length, so the parse-back masks
 * the text once and slices both together.
 */
type Scanned = { text: string; structure: string };

function sliceOf(s: Scanned, start: number, end = s.text.length): Scanned {
  return {
    text: s.text.slice(start, end),
    structure: s.structure.slice(start, end),
  };
}

// Ends are never inside quotes, so trimming both alike keeps them aligned.
function trimmed(s: Scanned): Scanned {
  let start = 0;
  let end = s.text.length;
  while (start < end && WHITESPACE.test(s.text[start])) {
    start++;
  }
  while (end > start && WHITESPACE.test(s.text[end - 1])) {
    end--;
  }
  return sliceOf(s, start, end);
}

function unwrapOperand(raw: string): string {
  const s = raw.trim();

  // Template references stay as-is
  if (s.startsWith("{{") && s.endsWith("}}")) {
    return s;
  }

  // Remove surrounding double quotes
  if (s.startsWith('"') && s.endsWith('"')) {
    return s.slice(1, -1).replace(/\\"/g, '"').replace(/\\\\/g, "\\");
  }

  // Remove surrounding single quotes
  if (s.startsWith("'") && s.endsWith("'")) {
    return s.slice(1, -1);
  }

  return s;
}

// A regex pattern only reopens as a rule when it is one complete literal that
// decodes exactly; anything else stays a typed expression.
function unwrapRegexOperand(raw: string): string | undefined {
  const s = raw.trim();
  if (!s.startsWith('"')) {
    return;
  }
  try {
    const scanned = scanString(s, 0);
    return scanned.next === s.length && !scanned.lossy
      ? scanned.value
      : undefined;
  } catch {
    return;
  }
}

// The whole expression is one matchesRegex(left, "pattern") call.
function parseRegexCall({ text: s, structure }: Scanned): ConditionRule | null {
  const [call] = regexCallsIn(structure, 1);
  if (call?.open !== "matchesRegex".length || call.close !== s.length - 1) {
    return null;
  }
  if (call.args.length !== 2) {
    return null;
  }
  const [[leftStart, leftEnd], [patternStart, patternEnd]] = call.args;
  const pattern = unwrapRegexOperand(s.slice(patternStart, patternEnd));
  return pattern === undefined
    ? null
    : makeRule(
        unwrapOperand(s.slice(leftStart, leftEnd)),
        "matchesRegex",
        pattern
      );
}

/**
 * Split an expression at top-level `&&` or `||` (depth-0 only).
 * Returns the parts and the detected logic operator, or null if
 * neither `&&` nor `||` appears at depth 0.
 */
function splitTopLevel(
  expr: Scanned
): { parts: Scanned[]; logic: "AND" | "OR" } | null {
  const { structure } = expr;
  let depth = 0;
  const parts: Scanned[] = [];
  let partStart = 0;
  let detectedLogic: "AND" | "OR" | null = null;

  for (let i = 0; i < structure.length; i++) {
    if (structure[i] === "(") {
      depth++;
    } else if (structure[i] === ")") {
      depth--;
    } else if (depth === 0) {
      const separator = structure.slice(i, i + 4);
      const logic =
        (separator === " && " && "AND") ||
        (separator === " || " && "OR") ||
        null;
      if (logic) {
        if (detectedLogic && detectedLogic !== logic) {
          return null; // mixed operators at same level — can't parse
        }
        detectedLogic = logic;
        parts.push(trimmed(sliceOf(expr, partStart, i)));
        partStart = i + 4;
        i += 3; // skip the separator
      }
    }
  }

  const last = trimmed(sliceOf(expr, partStart));
  if (last.text) {
    parts.push(last);
  }

  if (detectedLogic === null || parts.length === 0) {
    return null;
  }

  return { parts, logic: detectedLogic };
}

/** Strip one layer of balanced outer parentheses if present. */
function stripOuterParens(s: Scanned): Scanned {
  const whole = trimmed(s);
  const { text, structure } = whole;
  if (!(text.startsWith("(") && text.endsWith(")"))) {
    return whole;
  }
  let depth = 0;
  for (let i = 0; i < text.length - 1; i++) {
    if (structure[i] === "(") {
      depth++;
    } else if (structure[i] === ")") {
      depth--;
    }
    if (depth === 0) {
      return whole; // closing paren matched before end — not wrapping
    }
  }
  return trimmed(sliceOf(whole, 1, text.length - 1));
}

function makeRule(
  left: string,
  op: ConditionOperator,
  right = ""
): ConditionRule {
  return {
    id: nanoid(),
    leftOperand: left,
    operator: op,
    rightOperand: right,
  };
}

/** Try to parse a single atomic expression into a ConditionRule. */
function parseAtomicExpression(expr: Scanned): ConditionRule | null {
  const whole = trimmed(expr);
  const s = whole.text;

  if (s.startsWith("matchesRegex(")) {
    return parseRegexCall(whole);
  }
  if (s.startsWith("!matchesRegex(")) {
    const rule = parseRegexCall(sliceOf(whole, 1));
    return rule && { ...rule, operator: "notMatchesRegex" };
  }

  // String methods: String(left).includes(right), .startsWith(right), .endsWith(right)
  const stringMethodMatch = s.match(STRING_METHOD_PATTERN);
  if (stringMethodMatch) {
    const methodMap: Record<string, ConditionOperator> = {
      includes: "contains",
      startsWith: "startsWith",
      endsWith: "endsWith",
    };
    const op = methodMap[stringMethodMatch[2]];
    if (op) {
      return makeRule(
        unwrapOperand(stringMethodMatch[1]),
        op,
        unwrapOperand(stringMethodMatch[3])
      );
    }
  }

  // Unary existence patterns (wrapped in parens, already stripped by caller or not)
  const stripped = stripOuterParens(whole).text;

  // isEmpty: left === null || left === undefined || left === ""
  const isEmptyMatch = stripped.match(IS_EMPTY_PATTERN);
  if (isEmptyMatch) {
    return makeRule(unwrapOperand(isEmptyMatch[1]), "isEmpty");
  }

  // isNotEmpty: left !== null && left !== undefined && left !== ""
  const isNotEmptyMatch = stripped.match(IS_NOT_EMPTY_PATTERN);
  if (isNotEmptyMatch) {
    return makeRule(unwrapOperand(isNotEmptyMatch[1]), "isNotEmpty");
  }

  // exists: left !== null && left !== undefined
  const existsMatch = stripped.match(EXISTS_PATTERN);
  if (existsMatch) {
    return makeRule(unwrapOperand(existsMatch[1]), "exists");
  }

  // doesNotExist: left === null || left === undefined
  const doesNotExistMatch = stripped.match(DOES_NOT_EXIST_PATTERN);
  if (doesNotExistMatch) {
    return makeRule(unwrapOperand(doesNotExistMatch[1]), "doesNotExist");
  }

  // Single-clause null/undefined checks (must run after the two-clause
  // exists/doesNotExist patterns above so those win first).
  const isNotNullMatch = stripped.match(IS_NOT_NULL_PATTERN);
  if (isNotNullMatch) {
    return makeRule(unwrapOperand(isNotNullMatch[1]), "isNotNull");
  }

  const isNullMatch = stripped.match(IS_NULL_PATTERN);
  if (isNullMatch) {
    return makeRule(unwrapOperand(isNullMatch[1]), "isNull");
  }

  const isNotUndefinedMatch = stripped.match(IS_NOT_UNDEFINED_PATTERN);
  if (isNotUndefinedMatch) {
    return makeRule(unwrapOperand(isNotUndefinedMatch[1]), "isNotUndefined");
  }

  const isUndefinedMatch = stripped.match(IS_UNDEFINED_PATTERN);
  if (isUndefinedMatch) {
    return makeRule(unwrapOperand(isUndefinedMatch[1]), "isUndefined");
  }

  // Comparison operators: left op right
  const comparisonMatch = s.match(COMPARISON_PATTERN);
  if (comparisonMatch) {
    return makeRule(
      unwrapOperand(comparisonMatch[1]),
      comparisonMatch[2] as ConditionOperator,
      unwrapOperand(comparisonMatch[3])
    );
  }

  // Bare value (e.g. template ref, variable) — treat as truthy check via "exists"
  const bareValue = unwrapOperand(s);
  if (bareValue) {
    return makeRule(bareValue, "exists");
  }

  return null;
}

function parseExpression(expr: Scanned): ConditionGroup | ConditionRule | null {
  const s = trimmed(expr);
  if (!s.text || s.text === "true") {
    return null;
  }

  // Try splitting at top-level && / ||
  const split = splitTopLevel(s);
  if (split) {
    const rules: (ConditionRule | ConditionGroup)[] = [];
    for (const part of split.parts) {
      const stripped = stripOuterParens(part);
      const parsed = parseExpression(stripped);
      if (parsed === null) {
        return null; // bail if any part is unparseable
      }
      rules.push(parsed);
    }
    return { id: nanoid(), logic: split.logic, rules };
  }

  // Single expression — try to parse as atomic rule
  const rule = parseAtomicExpression(s);
  if (rule) {
    return rule;
  }

  // Try stripping outer parens and re-parsing (for parenthesized single expressions)
  const stripped = stripOuterParens(s);
  if (stripped.text !== s.text) {
    return parseExpression(stripped);
  }

  return null;
}

/** How many rules in the group, nested groups included, test a regex. */
export function countRegexRules(group: ConditionGroup): number {
  let count = 0;
  for (const item of group.rules) {
    if (isConditionGroup(item)) {
      count += countRegexRules(item);
    } else if (isRegexOperator(item.operator)) {
      count += 1;
    }
  }
  return count;
}

function groupUsesRegex(group: ConditionGroup): boolean {
  return countRegexRules(group) > 0;
}

type EditorConditionState = {
  /** Rules parsed from the condition text, to save with the node. */
  parsedGroup: ConditionGroup | null;
  initialMode: "visual" | "expression";
};

/**
 * How the editor opens a condition: saved rules, rules parsed from its text,
 * or text. With regex involved, parsed rules must rebuild the exact text.
 */
export function editorConditionState(
  condition: string,
  savedGroup: ConditionGroup | undefined
): EditorConditionState {
  if (!condition) {
    return { parsedGroup: null, initialMode: "visual" };
  }
  if (savedGroup && visualConditionToExpression(savedGroup) === condition) {
    return { parsedGroup: null, initialMode: "visual" };
  }
  // The comparison parse rescans to a line break per operator; long text
  // with one opens as text, which the editor shows as typed.
  if (condition.length > MAX_PARSED_MULTILINE && LINE_BREAK.test(condition)) {
    return { parsedGroup: null, initialMode: "expression" };
  }
  // Masked once; every check and the parse-back read this.
  const masked = maskedStructure(condition);
  const scan: Scanned = { text: condition, structure: masked ?? condition };
  const parsed = masked === undefined ? null : groupFromScanned(scan);
  // The text is checked too: a garbled parse can swallow a regex call, or the
  // old new RegExp form, whole.
  const involvesRegex =
    mentionsRegexIn(scan.structure) ||
    REGEX_OBJECT_RE.test(scan.structure) ||
    (parsed !== null && groupUsesRegex(parsed));
  // More regex tests than a run allows stays text: the run refuses it, and
  // thousands of rule rows would freeze the editor.
  const tooManyRegex =
    masked !== undefined &&
    regexCallsIn(masked, MAX_REGEX_CALLS + 1).length > MAX_REGEX_CALLS;
  const usable =
    parsed !== null &&
    !tooManyRegex &&
    (!involvesRegex || visualConditionToExpression(parsed) === condition);
  return usable
    ? { parsedGroup: parsed, initialMode: "visual" }
    : { parsedGroup: null, initialMode: "expression" };
}

/**
 * Parse a condition expression string into a ConditionGroup.
 * Returns null if the expression cannot be parsed into visual form.
 */
export function expressionToConditionGroup(
  expression: string
): ConditionGroup | null {
  const structure = maskedStructure(expression);
  // A quote that is never closed leaves no structure to read rules from.
  return structure === undefined
    ? null
    : groupFromScanned({ text: expression, structure });
}

function groupFromScanned(expression: Scanned): ConditionGroup | null {
  const whole = trimmed(expression);
  if (!whole.text) {
    return null;
  }

  const result = parseExpression(whole);
  if (result === null) {
    return null;
  }

  // If result is already a group, return it
  if (isConditionGroup(result)) {
    return result;
  }

  // Wrap single rule in a group
  return { id: nanoid(), logic: "AND", rules: [result] };
}
